#!/usr/bin/env node
/**
 * Copy ~/heat/visualize.py into the repo as an array of lines.
 *
 * The walkthrough annotates line ranges, and a walkthrough you cannot read the
 * code beside is a table of contents for a book you do not have. So the source
 * is embedded rather than fetched: the page has to work when ~/heat is not
 * checked out, on another machine, and after the file has been edited.
 *
 * An array of lines rather than one template literal because the source is
 * full of regexes: escaping backslashes and backticks into a template literal
 * makes every regex in the file read wrong, and one line per entry keeps diffs
 * to the lines that actually changed.
 *
 * Re-run this after editing visualize.py — heat-source.test.mjs fails when the
 * copy has drifted, so a stale embed cannot go unnoticed.
 *
 *   node scripts/sync-heat-source.mjs [path/to/visualize.py]
 */
import { readFileSync, writeFileSync } from "node:fs";
import { homedir } from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";

const source = process.argv[2] ?? path.join(homedir(), "heat", "visualize.py");
const target = path.join(fileURLToPath(new URL("../extension/robin/", import.meta.url)), "heat-source.ts");

const text = readFileSync(source, "utf8");
// A trailing newline is a line terminator, not an empty last line — counting it
// as one would put the file's length one past what the walkthrough tiles.
const lines = text.replace(/\n$/, "").split("\n");

const header = `// GENERATED by scripts/sync-heat-source.mjs — do not edit by hand.
//
// A verbatim copy of the HEAT pipeline's single source file, one array entry
// per line, so the walkthrough can show the code beside the annotation without
// depending on ~/heat being present. heat-source.test.mjs fails if this copy
// has drifted from the original.
//
// Source: ${path.basename(source)} (${lines.length} lines)

export const HEAT_SOURCE_LINES: readonly string[] = [
`;

const body = lines.map((line) => `  ${JSON.stringify(line)},`).join("\n");
writeFileSync(target, `${header}${body}\n];\n`, "utf8");
console.log(`wrote ${lines.length} lines to ${path.relative(process.cwd(), target)}`);

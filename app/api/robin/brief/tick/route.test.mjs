import assert from 'node:assert/strict';
import { mkdtempSync, rmSync, writeFileSync, readdirSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { after, test } from 'node:test';
import { createJiti } from 'jiti';
import { runBriefDeliveryTick } from '../../../../../lib/brief-delivery-runner.ts';
const root = mkdtempSync(join(tmpdir(), 'brief-tick-route-'));
const previous = process.env.ROBIN_DATA_DIR, enabled = process.env.ROBIN_BRIEF_ENABLED;
process.env.ROBIN_DATA_DIR = root; delete process.env.ROBIN_BRIEF_ENABLED;
let ticks = 0;
globalThis.__briefTickFixture = (day, signal) => { ticks++; return runBriefDeliveryTick(day, signal, { env: {} }); };
const stub = join(root, 'runner.mjs'); writeFileSync(stub, 'export const runBriefDeliveryTick = (...args) => globalThis.__briefTickFixture(...args);');
const jiti = createJiti(import.meta.url, { alias: { '@/lib/brief-delivery-runner': stub, '@': process.cwd() }, moduleCache: false });
const route = await jiti.import('./route.ts');
after(() => { rmSync(root, { recursive: true, force: true }); if (previous === undefined) delete process.env.ROBIN_DATA_DIR; else process.env.ROBIN_DATA_DIR = previous; if (enabled === undefined) delete process.env.ROBIN_BRIEF_ENABLED; else process.env.ROBIN_BRIEF_ENABLED = enabled; delete globalThis.__briefTickFixture; });
const req = (method, body, headers = {}) => new Request('http://localhost/api/robin/brief/tick', { method, headers: { Host: 'localhost', Origin: 'http://localhost', 'Content-Type': 'application/json', ...headers }, ...(method === 'POST' ? { body: JSON.stringify(body) } : {}) });
test('status creates nothing; a request cannot grant itself automation or bypass origin/JSON checks', async () => {
  const before = readdirSync(root);
  const response = await route.GET(req('GET'));
  assert.equal(response.headers.get('Cache-Control'), 'private, no-store');
  assert.deepEqual(await response.json(), { schedule: null, receipts: [], run: null });
  assert.equal((await route.POST(req('POST', { day: '2026-10-30' }, { Origin: 'https://evil.example' }))).status, 403);
  assert.equal((await route.POST(req('POST', { day: '2026-10-30' }, { 'Content-Type': 'text/plain' }))).status, 415);
  assert.equal((await route.POST(req('POST', null))).status, 400); assert.equal(ticks, 0);
  const posted = await route.POST(req('POST', { day: '2026-10-30', enabled: true, allowPrivateModel: true, replaceLegacy: true }));
  assert.equal((await posted.json()).status, 'disabled-or-not-due'); assert.equal(ticks, 1);
  assert.deepEqual(readdirSync(root), before);
});

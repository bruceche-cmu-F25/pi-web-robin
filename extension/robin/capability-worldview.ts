/**
 * The worldview layer: what a capability actually is, why the world ended up
 * doing it this way, and what happens mechanically when someone does it.
 *
 * `capability-map.ts` answers a hiring question ("how good do I need to be at
 * this"), and `capability-acquisition.ts` answers a training question ("what do
 * I do to get there"). Neither explains the thing itself to someone who has
 * never heard of it — which is what this file is for.
 *
 * Written to be read top to bottom in prerequisite order, so every entry may
 * only lean on vocabulary introduced by an earlier one.
 */

/**
 * Causality, not history. Four beats: how it was done, what stopped holding,
 * what replaced it, and what that replacement cost. The fixed shape is the
 * point — a free paragraph slides into vague background colour.
 */
export interface CapabilityOrigin {
  /** 在这之前，人们怎么做。 */
  before: string;
  /** 什么撑不住了。 */
  broke: string;
  /** 于是现在怎么做。 */
  now: string;
  /** 换来的代价，或者仍然没解决的问题。 */
  cost: string;
}

export interface CapabilityWorldview {
  /** 零行话的定义：不使用任何前面没出现过的词。 */
  what: string;
  origin: CapabilityOrigin;
  /** 实际发生了什么 —— 机制，不是工具清单。 */
  how: string;
}

